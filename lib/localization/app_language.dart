  List<String> get monthNames =>
      _resolveList(_monthNamesByLanguage, effectiveLanguageCode) ??
      _italianMonthNames;

  List<String> get monthNamesForDates =>
      _resolveList(_monthNamesForDatesByLanguage, effectiveLanguageCode) ??
      _italianMonthNamesForDates;

  static List<T>? _resolveList<T>(
    Map<String, List<T>> table,
    String languageCode,
  ) {
    final direct = table[languageCode];
    if (direct != null) return direct;

    final fallback = _languageFallback[languageCode];
    if (fallback != null) return _resolveList(table, fallback);

    return null;
  }

  String categoryLabel(String storedName) {
    if (effectiveLanguageCode == italian) return storedName;

    return _resolveTranslation(
          _categoryTranslations[storedName],
          effectiveLanguageCode,
        ) ??
        storedName;
  }
}

String l(String italianText) {
  final lang = AppLanguageController.instance.effectiveLanguageCode;
  if (lang == AppLanguageController.italian) return italianText;

  return _resolveTranslation(_translations[italianText], lang) ?? italianText;
}

String le(String italianText, String englishText) {
  return AppLanguageController.instance.isEnglish ? englishText : italianText;
}

String localizedCategory(String storedName) {
  return AppLanguageController.instance.categoryLabel(storedName);
}

// Cerca la traduzione per la lingua richiesta dentro la mappa di una
// singola voce del dizionario (lingua -> testo tradotto), ripiegando
// sulla lingua base indicata in _languageFallback quando la voce per
// questa lingua specifica non è ancora stata scritta. Se anche quella
// manca, il chiamante ricade sul testo italiano originale.
String? _resolveTranslation(
  Map<String, String>? entry,
  String languageCode,
) {
  if (entry == null) return null;

  final direct = entry[languageCode];
  if (direct != null) return direct;

  final fallback = AppLanguageController._languageFallback[languageCode];
  if (fallback != null) return _resolveTranslation(entry, fallback);

  return null;
}

