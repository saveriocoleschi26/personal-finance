  static const Map<String, String> _languageFallback = {
    englishUK: englishUS,
  };

  static const Set<String> _rtlLanguages = {arabic};

  String _preference = system;

  String get preference => _preference;

  String get systemLanguageCode {
    final locale = WidgetsBinding.instance.platformDispatcher.locale;
    return _matchSystemLocale(locale);
  }

  static String _matchSystemLocale(Locale locale) {
    final languageCode = locale.languageCode;
    final countryCode = locale.countryCode;

    switch (languageCode) {
      case 'it':
        return italian;
      case 'en':
        return countryCode == 'GB' ? englishUK : englishUS;
      case 'fr':
        return french;
      case 'es':
        return spanish;
      case 'de':
        return german;
      case 'zh':
        return chineseSimplified;
      case 'pt':
        return countryCode == 'BR' ? portugueseBR : portuguesePT;
      case 'ja':
        return japanese;
      case 'ar':
        return arabic;
      case 'ru':
        return russian;
      default:
        return italian;
    }
  }

  String get effectiveLanguageCode {
    if (_preference == system) return systemLanguageCode;
    return _preference;
  }

  // Mantenuto per compatibilità con tutto il codice esistente che usa
  // le()/isEnglish per il testo in inglese scritto direttamente inline
  // (invece di passare dal dizionario centrale): resta vero per entrambe
  // le varianti inglesi, così quelle chiamate continuano a funzionare
  // esattamente come prima.
  bool get isEnglish =>
      effectiveLanguageCode == englishUS || effectiveLanguageCode == englishUK;

  bool get isRTL => _rtlLanguages.contains(effectiveLanguageCode);

  @override
  void didChangeLocales(List<Locale>? locales) {
    if (_preference == system) {
      notifyListeners();
    }
  }

  Future<void> load() async {
    final saved = await DatabaseService.instance.getSetting('language_code');

    // Chi aveva già scelto "Inglese" prima di questa versione ha salvato il
    // vecchio codice 'en': lo portiamo su en-US invece di perderlo (senza
    // questa riga, non essendo più in supportedLanguages, ricadrebbe in
    // automatico su "system" e l'utente vedrebbe la sua scelta sparire).
    if (saved == 'en') {
      _preference = englishUS;
      return;
    }

    if (saved == system || supportedLanguages.contains(saved)) {
      _preference = saved!;
    }
  }

  Future<void> setPreference(String value) async {
    if (value != system && !supportedLanguages.contains(value)) return;
    if (_preference == value) return;

    _preference = value;
    notifyListeners();
    await DatabaseService.instance.setSetting('language_code', value);
  }

